$ErrorActionPreference = "Stop"

$Root = "c:\Users\hirat\Workspace\Antigravity\memorychk_shakai"
$Proj = Join-Path $Root "project"
$DataOutDir = Join-Path $Root "data"
New-Item -ItemType Directory -Force -Path $DataOutDir | Out-Null

function Merge-JsonArrayDirs([string[]]$DirPaths) {
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.Append("[")
    $first = $true
    $count = 0
    foreach ($dir in $DirPaths) {
        if (-not (Test-Path $dir)) { continue }
        Get-ChildItem -Path $dir -Filter "*.json" | Sort-Object Name | ForEach-Object {
            $raw = (Get-Content -Path $_.FullName -Raw -Encoding UTF8).Trim()
            $parsed = $raw | ConvertFrom-Json
            $items = if ($parsed -is [System.Array]) { $parsed } else { @($parsed) }
            $count += $items.Count
            if ($raw.StartsWith("[") -and $raw.EndsWith("]")) {
                $inner = $raw.Substring(1, $raw.Length - 2).Trim()
                if ($inner.Length -gt 0) {
                    if (-not $first) { [void]$sb.Append(",") }
                    $first = $false
                    [void]$sb.Append($inner)
                }
            }
        }
    }
    [void]$sb.Append("]")
    return @{ Json = $sb.ToString(); Count = $count }
}

$unitsMaster = (Get-Content -Path (Join-Path $Proj "data\units_master.json") -Raw -Encoding UTF8).Trim()
$prefsMaster = (Get-Content -Path (Join-Path $Proj "data\prefs_master.json") -Raw -Encoding UTF8).Trim()
$mergedExDiag = Merge-JsonArrayDirs @((Join-Path $Proj "data\units"), (Join-Path $Proj "data\diag"))
$mergedGame = Merge-JsonArrayDirs @((Join-Path $Proj "data\game"))

# assets/prefs/pref_XX.jpg と assets/left/left_XX.jpg と assets/figs/*.jpg を自動スキャン
$prefImgs = @{}
if (Test-Path (Join-Path $Root "assets\prefs")) {
    Get-ChildItem -Path (Join-Path $Root "assets\prefs") -Filter "pref_*.jpg" | ForEach-Object {
        if ($_.BaseName -match '^pref_(\d{2})$') {
            $code = [int]$Matches[1]
            $prefImgs["$code"] = "assets/prefs/$($_.Name)"
        }
    }
}
$leftImgs = @{}
if (Test-Path (Join-Path $Root "assets\left")) {
    Get-ChildItem -Path (Join-Path $Root "assets\left") -Filter "left_*.jpg" | ForEach-Object {
        if ($_.BaseName -match '^left_(\d{2})$') {
            $uid = [int]$Matches[1]
            $leftImgs["$uid"] = "assets/left/$($_.Name)"
        }
    }
}
$figImgs = @{}
if (Test-Path (Join-Path $Root "assets\figs")) {
    Get-ChildItem -Path (Join-Path $Root "assets\figs") -Filter "*.jpg" | ForEach-Object {
        $figImgs[$_.BaseName] = "assets/figs/$($_.Name)"
    }
}

$prefImgsJson = if ($prefImgs.Count -gt 0) { ConvertTo-Json -InputObject $prefImgs -Compress } else { "{}" }
$leftImgsJson = if ($leftImgs.Count -gt 0) { ConvertTo-Json -InputObject $leftImgs -Compress } else { "{}" }
$figImgsJson  = if ($figImgs.Count -gt 0)  { ConvertTo-Json -InputObject $figImgs  -Compress } else { "{}" }

$js = @"
// Auto-generated by project/scripts/build_shakai.ps1
window.SHAKAI_DB = {
  unitsMaster: $unitsMaster,
  prefsMaster: $prefsMaster,
  questions: $($mergedExDiag.Json),
  gameQuestions: $($mergedGame.Json),
  prefImages: $prefImgsJson,
  leftImages: $leftImgsJson,
  figImages: $figImgsJson
};
"@

$outFile = Join-Path $DataOutDir "shakai_db.js"
[IO.File]::WriteAllText($outFile, $js, [System.Text.UTF8Encoding]::new($false))
$kb = [Math]::Round((Get-Item $outFile).Length / 1KB, 1)
Write-Host "Built $outFile ($kb KB)"
Write-Host "  Ex+Diag Qs: $($mergedExDiag.Count), Game 4-choice Qs: $($mergedGame.Count)"
Write-Host "  Pref art images: $($prefImgs.Count), Left study imgs: $($leftImgs.Count), Figs: $($figImgs.Count)"
